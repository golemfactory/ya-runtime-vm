"""Prepare a pinned OpenVMM checkout and the patched KVM Cargo overrides."""
import copy
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CONFIG = ROOT / "patches/openvmm/config.toml"
DESTINATION = ROOT / "build/openvmm"


def git(directory, *args):
    return subprocess.check_output(
        ["git", "-C", str(directory), *args], stderr=subprocess.PIPE
    )


def digest(data):
    return hashlib.sha256(data).hexdigest()


def toml_value(value):
    if isinstance(value, dict):
        return "{ " + ", ".join(
            f"{json.dumps(key)} = {toml_value(item)}" for key, item in value.items()
        ) + " }"
    if isinstance(value, list):
        return "[" + ", ".join(map(toml_value, value)) + "]"
    return json.dumps(value)


def standalone_manifest(package, workspace, config, runtime_workspace="../../../.."):
    """Keep upstream settings, but use one git source for OpenVMM dependencies.

    Leaving workspace path dependencies in place would compile a second copy of
    virt/guestmem/etc. whose Rust types differ from the runtime's git packages.
    """
    package = copy.deepcopy(package)
    for name, value in package["package"].items():
        if isinstance(value, dict) and value.get("workspace"):
            package["package"][name] = workspace["package"][name]

    sections = [package, *package.get("target", {}).values()]
    for section in sections:
        for kind in ("dependencies", "dev-dependencies", "build-dependencies"):
            for name, value in section.get(kind, {}).items():
                if not isinstance(value, dict) or not value.get("workspace"):
                    continue
                inherited = copy.deepcopy(workspace["dependencies"][name])
                if isinstance(inherited, str):
                    inherited = {"version": inherited}
                extra_features = value.get("features", [])
                features = inherited.get("features", []) + extra_features
                inherited.update({k: v for k, v in value.items() if k != "workspace"})
                if features:
                    inherited["features"] = list(dict.fromkeys(features))
                if "path" in inherited:
                    del inherited["path"]
                    inherited.update(git=config["repository"], rev=config["revision"])
                section[kind][name] = inherited

    if package.get("lints", {}).get("workspace"):
        package["lints"] = workspace["lints"]
    # Join the runtime workspace so its lockfile also covers our regression tests.
    package["package"]["workspace"] = runtime_workspace
    lines = ["# Generated by scripts/prepare_openvmm.py; do not edit."]

    def emit(table, path):
        if path:
            lines.append("\n[" + ".".join(map(json.dumps, path)) + "]")
        for key, value in table.items():
            if not isinstance(value, dict):
                lines.append(f"{json.dumps(key)} = {toml_value(value)}")
        for key, value in table.items():
            if isinstance(value, dict):
                emit(value, [*path, key])

    emit(package, [])
    return "\n".join(lines) + "\n"


def checkout_state(directory):
    return {
        "revision": git(directory, "rev-parse", "HEAD").decode().strip(),
        "diff": digest(git(directory, "diff", "--binary", "HEAD", "--")),
        "untracked": git(directory, "ls-files", "--others", "--exclude-standard").decode(),
    }


def prepare(config_path=CONFIG, destination=DESTINATION):
    config = tomllib.loads(config_path.read_text())
    patch = config_path.parent / config["patch"]
    inputs = digest(config_path.read_bytes() + patch.read_bytes() + Path(__file__).read_bytes())
    destination.parent.mkdir(parents=True, exist_ok=True)
    lock = destination.with_name(destination.name + ".prepare-lock")
    try:
        lock.mkdir()
    except FileExistsError:
        raise RuntimeError(f"Preparation already running (or stale lock): {lock}") from None
    staging = None
    try:
        verified_local = False
        if destination.exists():
            stamp = destination / ".git/ya-runtime-vm-prepare.json"
            if not stamp.is_file():
                raise RuntimeError(f"Refusing to replace an unmanaged checkout: {destination}")
            saved = json.loads(stamp.read_text())
            if checkout_state(destination) != saved["state"]:
                raise RuntimeError(f"Checkout has local changes; preserve them before rebuilding: {destination}")
            if saved["inputs"] == inputs:
                print(f"OpenVMM {config['tag']} override is ready: {destination}")
                return
            verified_local = saved["state"].get("revision") == config["revision"]

        staging = Path(tempfile.mkdtemp(prefix=".openvmm-", dir=destination.parent))
        git(staging, "init", "--quiet")
        git(staging, "config", "core.autocrlf", "false")
        git(staging, "remote", "add", "origin", config["repository"])
        print(f"Fetching OpenVMM {config['tag']} ({config['revision']})", flush=True)
        try:
            git(staging, "fetch", "--depth=1", "origin", f"refs/tags/{config['tag']}")
        except subprocess.CalledProcessError:
            if not verified_local:
                raise
            git(staging, "fetch", "--quiet", "--depth=1", str(destination), config["revision"])
        actual = git(staging, "rev-parse", "FETCH_HEAD^{commit}").decode().strip()
        if actual != config["revision"]:
            raise RuntimeError(f"OpenVMM tag changed: expected {config['revision']}, got {actual}")
        git(staging, "checkout", "--quiet", "--detach", actual)
        git(staging, "apply", "--check", str(patch.resolve()))
        git(staging, "apply", "--index", str(patch.resolve()))
        workspace = tomllib.loads((staging / "Cargo.toml").read_text())["workspace"]
        # Keep the original single-crate configuration usable for local fixtures.
        crates = config["crates"] if "crates" in config else [config["crate"]]
        for crate in crates:
            manifest_path = staging / crate / "Cargo.toml"
            manifest = tomllib.loads(manifest_path.read_text())
            runtime_workspace = Path(os.path.relpath(ROOT, manifest_path.parent)).as_posix()
            manifest_path.write_text(
                standalone_manifest(manifest, workspace, config, runtime_workspace), newline="\n"
            )
        state = checkout_state(staging)
        if state["untracked"]:
            raise RuntimeError("Patch created unexpected untracked files")
        (staging / ".git/ya-runtime-vm-prepare.json").write_text(
            json.dumps({"inputs": inputs, "state": state}, indent=2) + "\n"
        )
        # Only replace a previously verified, generated checkout after success.
        if destination.exists():
            shutil.rmtree(destination, onexc=remove_readonly)
        staging.rename(destination)
        staging = None
        print(f"Prepared OpenVMM override: {destination}")
    finally:
        if staging is not None:
            shutil.rmtree(staging, onexc=remove_readonly)
        lock.rmdir()


def remove_readonly(function, path, error):
    """Git object files can be read-only on Windows."""
    import stat
    Path(path).chmod(stat.S_IWRITE | stat.S_IREAD)
    function(path)


if __name__ == "__main__":
    try:
        prepare()
    except subprocess.CalledProcessError as error:
        raise SystemExit(error.stderr.decode(errors="replace")) from error
    except RuntimeError as error:
        raise SystemExit(str(error)) from error
